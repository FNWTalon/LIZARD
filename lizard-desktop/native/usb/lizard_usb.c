// ai: lizard_usb (Windows): binds the WinUSB driver to the devices libusb needs on Windows and takes it off again,
// ai: through libwdi (Zadig's library, LGPL-3.0, linked statically; its source and build: ../../packaging/libwdi.sh).
// ai: libusb opens a USB device on Windows only through WinUSB (or libusbK): a phone shows Windows' MTP driver, the
// ai: phone in accessory mode (Google's 18D1:2D00, or 2D01 with adb, its accessory interface MI_00) none at all, and a
// ai: USB3 Vision camera (Aravis's, through libusb) none either.
// ai:   lizard_usb list                       every USB device libwdi sees, and LIZARD's INFs in the driver store, as JSON
// ai:   lizard_usb bind <vid>:<pid>[:<mi>]... WinUSB on each (hex ids, mi the interface of a composite device); a device
// ai:                                         not plugged in gets the driver staged for its next arrival
// ai:   lizard_usb unbind                     every LIZARD INF out of the driver store, the devices it drives removed and the
// ai:                                         bus scanned again, so each comes back with its own driver (MTP); the
// ai:                                         certificates the binds installed removed
// ai: bind and unbind need an administrator: run by a user, the program starts itself elevated (one UAC prompt) and hands
// ai: on its output and exit code. Each INF is lizard_<vid>_<pid>[_<mi>].inf, its catalog signed by a certificate libwdi
// ai: makes and installs as a trusted root and publisher (subject below), whose private key it discards. Output: one
// ai: JSON object on stdout; exit 0 every target done, 1 one failed, 2 usage, 3 the elevation refused or failed.
#define WIN32_LEAN_AND_MEAN
#include <windows.h>
#include <cfgmgr32.h>
#include <setupapi.h>
#include <shellapi.h>
#include <wincrypt.h>

#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#include "libwdi.h"

#define CERT_SUBJECT "CN=LIZARD USB (libwdi autogenerated)"
#define CERT_NAME_W L"LIZARD USB (libwdi autogenerated)"

static FILE* out;

static void jstr(const char* s) {
  fputc('"', out);
  for (const unsigned char* p = (const unsigned char*)(s ? s : ""); *p; p++) {
    if (*p == '"' || *p == '\\') fprintf(out, "\\%c", *p);
    else if (*p < 0x20) fprintf(out, "\\u%04x", *p);
    else fputc(*p, out);
  }
  fputc('"', out);
}

static BOOL elevated(void) {
  HANDLE t = NULL;
  TOKEN_ELEVATION e = {0};
  DWORD n = 0;
  BOOL yes = FALSE;
  if (OpenProcessToken(GetCurrentProcess(), TOKEN_QUERY, &t)) {
    if (GetTokenInformation(t, TokenElevation, &e, sizeof e, &n)) yes = e.TokenIsElevated != 0;
    CloseHandle(t);
  }
  return yes;
}

// ai: this program again as an administrator with the same arguments and --out <a temp file>; its output copied to ours
static int rerunElevated(int argc, wchar_t** argv) {
  wchar_t self[MAX_PATH], tmp[MAX_PATH], file[MAX_PATH], params[4096] = L"";
  if (!GetModuleFileNameW(NULL, self, MAX_PATH) || !GetTempPathW(MAX_PATH, tmp) || !GetTempFileNameW(tmp, L"liz", 0, file)) return 3;
  for (int i = 1; i < argc; i++) {
    if (wcslen(params) + wcslen(argv[i]) + 4 >= 4096) return 2;
    wcscat(params, L"\"");
    wcscat(params, argv[i]);
    wcscat(params, L"\" ");
  }
  if (wcslen(params) + wcslen(file) + 12 >= 4096) return 2;
  wcscat(params, L"--out \"");
  wcscat(params, file);
  wcscat(params, L"\"");
  SHELLEXECUTEINFOW sh = {0};
  sh.cbSize = sizeof sh;
  sh.fMask = SEE_MASK_NOCLOSEPROCESS | SEE_MASK_NO_CONSOLE;
  sh.lpVerb = L"runas";
  sh.lpFile = self;
  sh.lpParameters = params;
  sh.nShow = SW_HIDE;
  if (!ShellExecuteExW(&sh) || !sh.hProcess) {
    const DWORD err = GetLastError();
    DeleteFileW(file);
    fprintf(out, "{\"ok\":false,\"error\":");
    jstr(err == ERROR_CANCELLED ? "the administrator's prompt was declined" : "the program could not be started as an administrator");
    fprintf(out, "}\n");
    return 3;
  }
  WaitForSingleObject(sh.hProcess, INFINITE);
  DWORD code = 3;
  GetExitCodeProcess(sh.hProcess, &code);
  CloseHandle(sh.hProcess);
  FILE* f = _wfopen(file, L"rb");
  if (f) {
    char b[4096];
    size_t n;
    while ((n = fread(b, 1, sizeof b, f)) > 0) fwrite(b, 1, n, out);
    fclose(f);
  }
  DeleteFileW(file);
  return (int)code;
}

static BOOL isPhone(const struct wdi_device_info* d) {
  return (d->compatible_id && strstr(d->compatible_id, "MS_COMP_MTP")) || (d->vid == 0x18D1 && d->pid >= 0x2D00 && d->pid <= 0x2D05);
}

// ai: a USB3 Vision interface: class EF, subclass 05 (its control, event and streaming interfaces)
static BOOL isCamera(const struct wdi_device_info* d) {
  return d->compatible_id && strstr(d->compatible_id, "Class_EF&SubClass_05") != NULL;
}

// ai: the driver store's INFs (%windir%\INF\oem*.inf) that are LIZARD's: their catalog lizard_*.cat; the callback gets
// ai: each one's file name (oemNN.inf)
static void eachLizardInf(void (*fn)(const wchar_t* name, void* ctx), void* ctx) {
  wchar_t dir[MAX_PATH], pat[MAX_PATH];
  if (!GetWindowsDirectoryW(dir, MAX_PATH)) return;
  _snwprintf(pat, MAX_PATH, L"%ls\\INF\\oem*.inf", dir);
  WIN32_FIND_DATAW fd;
  HANDLE h = FindFirstFileW(pat, &fd);
  if (h == INVALID_HANDLE_VALUE) return;
  do {
    wchar_t path[MAX_PATH], cat[MAX_PATH] = L"";
    _snwprintf(path, MAX_PATH, L"%ls\\INF\\%ls", dir, fd.cFileName);
    GetPrivateProfileStringW(L"Version", L"CatalogFile", L"", cat, MAX_PATH, path);
    if (!_wcsnicmp(cat, L"lizard_", 7)) fn(fd.cFileName, ctx);
  } while (FindNextFileW(h, &fd));
  FindClose(h);
}

static void listInf(const wchar_t* name, void* ctx) {
  int* first = (int*)ctx;
  char n[MAX_PATH];
  WideCharToMultiByte(CP_UTF8, 0, name, -1, n, sizeof n, NULL, NULL);
  fprintf(out, "%s", *first ? "" : ",");
  jstr(n);
  *first = 0;
}

static int list(void) {
  struct wdi_device_info* devs = NULL;
  struct wdi_options_create_list o = {0};
  o.list_all = TRUE;
  o.trim_whitespaces = TRUE;
  const int r = wdi_create_list(&devs, &o);
  fprintf(out, "{\"ok\":%s,\"devices\":[", r == WDI_SUCCESS || r == WDI_ERROR_NO_DEVICE ? "true" : "false");
  int first = 1;
  for (struct wdi_device_info* d = r == WDI_SUCCESS ? devs : NULL; d; d = d->next) {
    fprintf(out, "%s{\"vid\":%u,\"pid\":%u,\"mi\":%d,\"desc\":", first ? "" : ",", d->vid, d->pid, d->is_composite ? d->mi : -1);
    jstr(d->desc);
    fprintf(out, ",\"driver\":");
    jstr(d->driver);
    fprintf(out, ",\"hardware_id\":");
    jstr(d->hardware_id);
    fprintf(out, ",\"compatible_id\":");
    jstr(d->compatible_id);
    fprintf(out, ",\"phone\":%s,\"camera\":%s,\"winusb\":%s}", isPhone(d) ? "true" : "false", isCamera(d) ? "true" : "false",
            d->driver && !_stricmp(d->driver, "WinUSB") ? "true" : "false");
    first = 0;
  }
  if (r == WDI_SUCCESS) wdi_destroy_list(devs);
  fprintf(out, "],\"installed\":[");
  first = 1;
  eachLizardInf(listInf, &first);
  fprintf(out, "]");
  if (r != WDI_SUCCESS && r != WDI_ERROR_NO_DEVICE) {
    fprintf(out, ",\"error\":");
    jstr(wdi_strerror(r));
  }
  fprintf(out, "}\n");
  return r == WDI_SUCCESS || r == WDI_ERROR_NO_DEVICE ? 0 : 1;
}

// ai: one target: WinUSB prepared in a folder of its own under %TEMP%\lizard_usb, then installed on the device that
// ai: matches it, or staged for it where none is plugged in
static int bindOne(const char* spec, struct wdi_device_info* devs, int* first) {
  unsigned vid = 0, pid = 0;
  int mi = -1;
  const int got = sscanf(spec, "%x:%x:%x", &vid, &pid, (unsigned*)&mi);
  if (got < 2 || vid > 0xFFFF || pid > 0xFFFF || (got == 3 && (mi < 0 || mi > 0xFF))) return 2;
  if (got < 3) mi = -1;
  struct wdi_device_info dev = {0};
  dev.vid = (unsigned short)vid;
  dev.pid = (unsigned short)pid;
  dev.is_composite = mi >= 0;
  dev.mi = (unsigned char)(mi >= 0 ? mi : 0);
  dev.desc = vid == 0x18D1 && pid >= 0x2D00 && pid <= 0x2D05 ? "Android accessory (LIZARD)" : "USB device (LIZARD)";
  for (struct wdi_device_info* d = devs; d; d = d->next)
    if (d->vid == dev.vid && d->pid == dev.pid && d->is_composite == dev.is_composite && (!dev.is_composite || d->mi == dev.mi)) {
      dev.hardware_id = d->hardware_id;
      dev.device_id = d->device_id;
      if (d->desc && *d->desc) dev.desc = d->desc;
      break;
    }
  char path[MAX_PATH], inf[64];
  char tmp[MAX_PATH];
  if (!GetTempPathA(MAX_PATH, tmp)) return 1;
  if (mi >= 0) {
    snprintf(inf, sizeof inf, "lizard_%04x_%04x_%02x.inf", vid, pid, mi);
    snprintf(path, sizeof path, "%slizard_usb\\%04x_%04x_%02x", tmp, vid, pid, mi);
  } else {
    snprintf(inf, sizeof inf, "lizard_%04x_%04x.inf", vid, pid);
    snprintf(path, sizeof path, "%slizard_usb\\%04x_%04x", tmp, vid, pid);
  }
  struct wdi_options_prepare_driver po = {0};
  po.driver_type = WDI_WINUSB;
  po.vendor_name = "LIZARD";
  po.cert_subject = CERT_SUBJECT;
  struct wdi_options_install_driver io = {0};
  io.pending_install_timeout = 120000;
  int r = wdi_prepare_driver(&dev, path, inf, &po);
  const char* step = "prepare";
  if (r == WDI_SUCCESS) { r = wdi_install_driver(&dev, path, inf, &io); step = "install"; }
  fprintf(out, "%s{\"target\":", *first ? "" : ",");
  jstr(spec);
  fprintf(out, ",\"present\":%s,\"ok\":%s", dev.device_id ? "true" : "false", r == WDI_SUCCESS ? "true" : "false");
  if (r != WDI_SUCCESS) {
    fprintf(out, ",\"error\":");
    char e[160];
    snprintf(e, sizeof e, "%s: %s", step, wdi_strerror(r));
    jstr(e);
  }
  fprintf(out, "}");
  *first = 0;
  return r == WDI_SUCCESS ? 0 : 1;
}

static int bind(int n, char** specs) {
  struct wdi_device_info* devs = NULL;
  struct wdi_options_create_list o = {0};
  o.list_all = TRUE;
  const int lr = wdi_create_list(&devs, &o);
  if (lr != WDI_SUCCESS) devs = NULL;
  int worst = 0, first = 1;
  fprintf(out, "{\"done\":[");
  for (int i = 0; i < n; i++) {
    const int r = bindOne(specs[i], devs, &first);
    if (r == 2) { worst = 2; break; }
    if (r) worst = 1;
  }
  if (devs) wdi_destroy_list(devs);
  fprintf(out, "],\"ok\":%s}\n", worst ? "false" : "true");
  return worst;
}

struct Unbind { int first, failed; };

// ai: every device (present or not) whose driver is this INF removed, then the INF out of the store
static void unbindInf(const wchar_t* name, void* ctx) {
  struct Unbind* u = (struct Unbind*)ctx;
  HDEVINFO set = SetupDiGetClassDevsW(NULL, L"USB", NULL, DIGCF_ALLCLASSES);
  int removed = 0;
  if (set != INVALID_HANDLE_VALUE) {
    SP_DEVINFO_DATA d;
    memset(&d, 0, sizeof d);
    d.cbSize = sizeof d;
    for (DWORD i = 0; SetupDiEnumDeviceInfo(set, i, &d); i++) {
      HKEY k = SetupDiOpenDevRegKey(set, &d, DICS_FLAG_GLOBAL, 0, DIREG_DRV, KEY_READ);
      if (k == INVALID_HANDLE_VALUE) continue;
      wchar_t infPath[MAX_PATH] = L"";
      DWORD sz = sizeof infPath, type = 0;
      const LONG q = RegQueryValueExW(k, L"InfPath", NULL, &type, (BYTE*)infPath, &sz);
      RegCloseKey(k);
      if (q == ERROR_SUCCESS && type == REG_SZ && !_wcsicmp(infPath, name) && SetupDiRemoveDevice(set, &d)) removed++;
    }
    SetupDiDestroyDeviceInfoList(set);
  }
  const BOOL ok = SetupUninstallOEMInfW(name, SUOI_FORCEDELETE, NULL);
  char n8[MAX_PATH];
  WideCharToMultiByte(CP_UTF8, 0, name, -1, n8, sizeof n8, NULL, NULL);
  fprintf(out, "%s{\"inf\":", u->first ? "" : ",");
  jstr(n8);
  fprintf(out, ",\"devices\":%d,\"ok\":%s}", removed, ok ? "true" : "false");
  u->first = 0;
  if (!ok) u->failed = 1;
}

// ai: the certificates the binds installed, out of the machine's Root and TrustedPublisher stores
static int dropCerts(void) {
  int n = 0;
  const wchar_t* stores[] = {L"Root", L"TrustedPublisher"};
  for (int s = 0; s < 2; s++) {
    HCERTSTORE st = CertOpenStore(CERT_STORE_PROV_SYSTEM_W, 0, 0, CERT_SYSTEM_STORE_LOCAL_MACHINE, stores[s]);
    if (!st) continue;
    PCCERT_CONTEXT c;
    while ((c = CertFindCertificateInStore(st, X509_ASN_ENCODING, 0, CERT_FIND_SUBJECT_STR_W, CERT_NAME_W, NULL)) != NULL)
      if (CertDeleteCertificateFromStore(c)) n++;   // ai: frees c either way
      else break;
    CertCloseStore(st, 0);
  }
  return n;
}

static int unbind(void) {
  struct Unbind u = {1, 0};
  fprintf(out, "{\"removed\":[");
  eachLizardInf(unbindInf, &u);
  const int certs = dropCerts();
  // ai: the bus scanned again: a device that lost its node comes back with the driver Windows chooses (MTP for a phone)
  DEVINST root;
  if (CM_Locate_DevNodeW(&root, NULL, CM_LOCATE_DEVNODE_NORMAL) == CR_SUCCESS) CM_Reenumerate_DevNode(root, CM_REENUMERATE_SYNCHRONOUS);
  fprintf(out, "],\"certificates\":%d,\"ok\":%s}\n", certs, u.failed ? "false" : "true");
  return u.failed;
}

int wmain(int argc, wchar_t** wargv) {
  out = stdout;
  // ai: arguments as UTF-8; --out <file> (the elevated run's) moves the output there
  char** argv = calloc((size_t)argc + 1, sizeof *argv);
  int n = 0;
  const wchar_t* outPath = NULL;
  for (int i = 0; i < argc; i++) {
    if (!wcscmp(wargv[i], L"--out") && i + 1 < argc) { outPath = wargv[++i]; continue; }
    const int len = WideCharToMultiByte(CP_UTF8, 0, wargv[i], -1, NULL, 0, NULL, NULL);
    argv[n] = malloc((size_t)len);
    WideCharToMultiByte(CP_UTF8, 0, wargv[i], -1, argv[n], len, NULL, NULL);
    n++;
  }
  if (outPath && !(out = _wfopen(outPath, L"wb"))) return 3;
  wdi_set_log_level(WDI_LOG_LEVEL_NONE);
  int rc = 2;
  if (n >= 2 && !strcmp(argv[1], "list") && n == 2) rc = list();
  else if (n >= 3 && !strcmp(argv[1], "bind")) rc = elevated() ? bind(n - 2, argv + 2) : rerunElevated(argc, wargv);
  else if (n == 2 && !strcmp(argv[1], "unbind")) rc = elevated() ? unbind() : rerunElevated(argc, wargv);
  else fprintf(stderr, "usage: lizard_usb list | bind <vid>:<pid>[:<mi>]... | unbind\n");
  if (out != stdout) fclose(out);
  return rc;
}
